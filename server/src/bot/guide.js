function intent(text){
 const s=String(text).trim().toLowerCase().replace(/[?!.,]+$/g,'');
 if(/^(что (ты )?умеешь|что такое esep|зачем (мне )?esep|чем (ты )?поможешь|в чем польза|в чём польза)$/.test(s))return 'value';
 if(/^(как (собрать|запросить|подготовить) документы|помоги с документами)$/.test(s))return 'docs';
 if(/^(как (перейти|войти) в (esep|есеп)|открыть esep)$/.test(s))return 'app';
 if(/^(задать вопрос|есть вопрос|вопрос|💬 задать вопрос)$/.test(s))return 'question';
 if(/^(что (мне )?(нужно )?сделать|что дальше|📍 что мне нужно сделать)$/.test(s))return 'next';
 return null;
}
